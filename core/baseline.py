
# ============================================================
# PATHFINDER SECURITY AUDITOR
# Module: Security Baseline Engine
#
# Purpose:
# Compare security findings against a predefined Windows
# security baseline and identify policy violations.
#
# The baseline is stored separately in config/baseline.json
# so security requirements can be changed without modifying
# the scanner's Python code.
#
# This module is READ-ONLY.
# ============================================================

import json
from pathlib import Path

from core.findings import Finding


def evaluate_baseline(findings: list[Finding]) -> dict:
    """
    Evaluate security findings against the configured baseline.

    Parameters:
        findings:
            A list of Finding objects generated by Pathfinder.

    Returns:
        A dictionary containing individual compliance results
        and summary statistics.

    This function does not execute PowerShell commands or
    modify Windows settings.
    """

    # --------------------------------------------------------
    # STEP 1: Locate the baseline configuration
    # --------------------------------------------------------

    # __file__ points to this Python file.
    # parent.parent moves from core/ to the project root.
    # This avoids relying on the current terminal directory.
    project_root = Path(__file__).resolve().parent.parent

    # Construct the complete path to the JSON configuration.
    baseline_path = project_root / "config" / "baseline.json"

    # Read the baseline configuration into a Python dictionary.
    with baseline_path.open("r", encoding="utf-8") as file:
        baseline = json.load(file)

    # --------------------------------------------------------
    # STEP 2: Index findings by check ID
    # --------------------------------------------------------

    # Convert the findings list into a dictionary.
    #
    # Example:
    # {
    #     "FW-001": Finding(...),
    #     "SMB-001": Finding(...),
    #     "BL-001": Finding(...)
    # }
    #
    # This lets us retrieve a finding directly using its ID.
    findings_by_id = {
        finding.check_id: finding
        for finding in findings
    }

    # Store the compliance assessment for each baseline rule.
    results = []

    # --------------------------------------------------------
    # STEP 3: Evaluate each security requirement
    # --------------------------------------------------------

    for rule in baseline["rules"]:

        # Identify which security check this rule applies to.
        check_id = rule["check_id"]

        # Find the corresponding scanner result.
        # .get() returns None when the check is missing.
        finding = findings_by_id.get(check_id)

        # CASE A: The required security check was not executed.
        #
        # Missing evidence must not be treated as compliance.
        if finding is None:
            result = "NOT_ASSESSED"
            actual_status = None

        # CASE B: The check encountered an execution error.
        #
        # An ERROR means Pathfinder could not verify the setting.
        # We must not classify it as compliant or non-compliant.
        elif finding.status == "ERROR":
            result = "ERROR"
            actual_status = finding.status

        # CASE C: The observed result meets the policy.
        elif finding.status == rule["required_status"]:
            result = "COMPLIANT"
            actual_status = finding.status

        # CASE D: The observed result violates the policy.
        else:
            result = "NON_COMPLIANT"
            actual_status = finding.status

        # Save the result together with the original rule.
        #
        # We retain both the expected and actual status so
        # the final report can explain the assessment.
        results.append({
            "check_id": check_id,
            "description": rule["description"],
            "required_status": rule["required_status"],
            "actual_status": actual_status,
            "result": result,
            "severity": rule["severity"]
        })

    # --------------------------------------------------------
    # STEP 4: Calculate compliance statistics
    # --------------------------------------------------------

    # Only successful assessments count toward the number
    # of assessed rules. Errors and missing checks are excluded.
    assessed = [
        item
        for item in results
        if item["result"] in ("COMPLIANT", "NON_COMPLIANT")
    ]

    # Count compliant rules.
    compliant_count = sum(
        item["result"] == "COMPLIANT"
        for item in assessed
    )

    # Count rules that violate the configured baseline.
    non_compliant_count = sum(
        item["result"] == "NON_COMPLIANT"
        for item in results
    )

    # Count baseline rules without corresponding findings.
    not_assessed_count = sum(
        item["result"] == "NOT_ASSESSED"
        for item in results
    )

    # Count checks that could not complete successfully.
    error_count = sum(
        item["result"] == "ERROR"
        for item in results
    )

    # --------------------------------------------------------
    # STEP 5: Return the complete baseline assessment
    # --------------------------------------------------------

    # The reporter will include this dictionary in the
    # machine-readable JSON security report.
    return {
        "baseline_name": baseline["baseline_name"],
        "baseline_version": baseline["baseline_version"],
        "compliant": compliant_count,
        "non_compliant": non_compliant_count,
        "not_assessed": not_assessed_count,
        "errors": error_count,
        "assessed": len(assessed),
        "rules": results
    }
